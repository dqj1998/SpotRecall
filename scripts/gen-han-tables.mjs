#!/usr/bin/env node
// Generate src/shared/han-tables.ts: Han characters that identify a query as
// Simplified Chinese vs Japanese. Derived from the national charsets via
// TextDecoder (needs Node with full ICU, the default build):
//   zh-only = GB2312 level 1 (3755 common hanzi) minus all of JIS X 0208
//   ja-only = JIS X 0208 level 1 (2965 common kanji) minus all of GB2312
// Shared characters (日, 本, 中, 国…) are in neither set. Re-run: node scripts/gen-han-tables.mjs

import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

function decodeRows(encoding, hiFrom, hiTo) {
  const dec = new TextDecoder(encoding);
  const out = new Set();
  for (let hi = hiFrom; hi <= hiTo; hi++) {
    for (let lo = 0xa1; lo <= 0xfe; lo++) {
      const ch = dec.decode(new Uint8Array([hi, lo]));
      if (ch.length === 1 && /\p{Script=Han}/u.test(ch)) out.add(ch);
    }
  }
  return out;
}

const gbLevel1 = decodeRows('gb2312', 0xb0, 0xd7);
const gbAll = decodeRows('gb2312', 0xb0, 0xf7);
const jisLevel1 = decodeRows('euc-jp', 0xb0, 0xcf);
const jisAll = decodeRows('euc-jp', 0xb0, 0xf4);
const zhOnly = [...gbLevel1].filter((c) => !jisAll.has(c)).join('');
const jaOnly = [...jisLevel1].filter((c) => !gbAll.has(c)).join('');

const out = `// GENERATED by scripts/gen-han-tables.mjs — do not edit.
// Han characters that occur in only one of Simplified Chinese / Japanese common use.

/** GB2312 level-1 hanzi absent from JIS X 0208 (e.g. 们 语 译 门 车). */
export const ZH_ONLY_HAN = '${zhOnly}';

/** JIS X 0208 level-1 kanji absent from GB2312 (e.g. 帯 図 飯 訳 駅). */
export const JA_ONLY_HAN = '${jaOnly}';
`;
const target = join(dirname(fileURLToPath(import.meta.url)), '../src/shared/han-tables.ts');
await writeFile(target, out);
console.log(`zh-only ${[...zhOnly].length}, ja-only ${[...jaOnly].length} -> ${target}`);
